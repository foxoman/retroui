## Arabic for the toolkit: the words on screen, as `retroui/core`'s `tr` finds them.
##
## Keys: the text of the label exactly as the code literal has it, with the
## mnemonic marks taken out the way `splitMnemonic` (retroui/core) and `bare`
## (photo/menus, photo/pscc) do it: each single `&` is dropped and `&&` becomes
## `&` ("&File" -> "File", "Patter&n..." -> "Pattern...", "Black && &White..."
## -> "Black & White..."). A literal whose `&` stands before a space
## ("Dust & Scratches") or in "B&W" is plain text and is kept as written.
## Keyboard shortcuts are never part of a key: `menuItem(label, shortcut)` takes
## them as a separate argument, and Retro Photo's `ci` (photo/pscc) and `item`
## (photo/menus) fill it from the key map (`photoshopKeys` in photo.nim, pairs
## such as ("Ctrl+N", "New...") looked up by the command name), so a key is
## the label alone. "...", ":" and the case are kept; so are the leading
## and trailing spaces of a fixed part glued to a value at run time
## ("Could not open " & name), and its Arabic keeps the same spaces.
## Translations carry no `&`, so they are safe to pass through `splitMnemonic`.
##
## The common words (OK, Cancel, Open, Save, Close, Yes, No, Apply, ...) live
## here only; examples/photo/lang_ar.nim does not repeat them.
##
## An app turns Arabic on with the kit's words and its own:
##
## ```nim
## import retroui, retroui/lang_ar
## const myArabic = [("&Greet", "تحية")]
## setUiLanguage("ar", @toolkitArabic, @myArabic)
## ```

