proc nikonHuffman(b: Bytes; m: Rd; meta, at, stop, w, h, bps: int; white: var float): seq[uint16] =
  ## Nikon's compressed numbers (lossless or lossy): Huffman-coded
  ## differences from the same color two pixels back (two rows up at a
  ## row's start), through the camera's curve.
  var p = meta
  let ver0 = b.at(p)
  let ver1 = b.at(p + 1)
  p += 2
  if ver0 == 0x49 or ver1 == 0x58: p += 2110
  var vpred: array[2, array[2, int]]
  for k in 0 .. 3: vpred[k shr 1][k and 1] = m.u16(p + 2 * k)
  p += 8
  # the curve: numbers to light (lossy files)
  var curve = newSeq[uint16](0x10000)
  for i in 0 ..< curve.len: curve[i] = uint16(i)
  var mx = (1 shl bps) and 0x7fff
  var step = mx
  let csize = m.u16(p)
  p += 2
  if csize > 1: step = mx div (csize - 1)
  if ver0 == 0x44 and (ver1 == 0x20 or (ver1 == 0x40 and step > 3)) and step > 0:
    var cmax = mx
    if ver1 == 0x40:
      step = step div 4
      cmax = cmax div 4
    for i in 0 ..< csize:
      if i * step < curve.len: curve[i * step] = uint16(m.u16(p + 2 * i))
    for i in 0 ..< cmax:
      let a = i - i mod step
      curve[i] = uint16((int(curve[a]) * (step - i mod step) + int(curve[min(a + step, 0xFFFF)]) * (i mod step)) div step)
    white = float(curve[max(0, cmax - 1)])
  elif ver0 != 0x46 and csize <= 0x4001:
    for i in 0 ..< csize: curve[i] = uint16(m.u16(p + 2 * i))
  var tree = if ver0 == 0x46: 2 else: 0
  if bps == 14: tree += 3
  var split = 0
  if ver0 == 0x44 and (ver1 == 0x20 or ver1 == 0x40):
    split = m.u16(meta + 562)
  var huff = huffOf(nikonTrees[tree][0 .. 15], nikonTrees[tree][16 .. 31])
  result = newSeq[uint16](w * h)
  var r = bitsAt(b, at, stop)
  let rp = uptr(result)
  let cp = uptr(curve)
  var hpred: array[2, int]
  for row in 0 ..< h:
    if split > 0 and row == split:
      huff = huffOf(nikonTrees[tree + 1][0 .. 15], nikonTrees[tree + 1][16 .. 31])
    let o = row * w
    for col in 0 ..< w:
      let i = r.decode(huff)
      let len = i and 15
      let shl1 = i shr 4
      var diff = ((r.get(len - shl1) shl 1) + 1) shl shl1 shr 1
      if len > 0 and (diff and (1 shl (len - 1))) == 0:
        diff -= (1 shl len) - (if shl1 == 0: 1 else: 0)
      if col < 2:
        vpred[row and 1][col] = (vpred[row and 1][col] + diff) and 0xFFFF
        hpred[col] = vpred[row and 1][col]
      else:
        hpred[col and 1] = (hpred[col and 1] + diff) and 0xFFFF
      let v = (hpred[col and 1] xor 0x8000) - 0x8000
      rp[o + col] = cp[clamp(v, 0, 0x3fff)]

proc nikonVisible(model: string; rawW: int): tuple[left, cut: int] =
  ## Columns that are not picture, on the left and the right (as dcraw
  ## knows them).
  let md = normalModel("Nikon", model)
  case md
  of "D1X": (0, 4)
  of "D40X", "D60", "D80", "D3000": (0, 4)
  of "D3", "D3S", "D700": (2, 4)
  of "D3100": (6, 28)
  of "D5000", "D90": (0, 42)
  of "D5100", "D7000", "COOLPIX A": (0, 44)
  of "D3200", "D600", "D610", "D800", "D800E": (0, 46)
  of "D4", "Df": (2, 52)
  of "D200": (1, 4)
  of "D300", "D300S": (0, 32)
  else:
    if md.startsWith("D2H"): (6, 14)
    elif md.startsWith("D2X"): (0, 8)
    elif md.startsWith("D40") or md.startsWith("D50") or md.startsWith("D70"): (0, 1)
    else: (0, 0)

proc readNef(data: string; b: Bytes): Sensor =
  let r = tiffOf(b)
  let first = r.base + r.u32(4)
  let ifd0 = r.dir(first)
  result.start(r, ifd0, "NEF")
  let raw = r.mosaicDir(r.dirsFrom(first))
  let w = int(r.get(raw, 256))
  let h = int(r.get(raw, 257))
  let bps = int(r.get(raw, 258, 12))
  let comp = int(r.get(raw, 259, 1))
  let (at, size) = r.stripsOf(raw)
  result.rawW = w
  result.rawH = h
  result.cfaOf(r, raw, [0, 1, 1, 2])
  # the maker's note: white balance, black, the curve
  var wb4: array[4, float]          # red, green, blue, green
  var black4: array[4, float]       # (red, green, green, blue)
  var meta = -1
  var mr = r
  let (mn, _) = r.makerNote(r.exifDir(ifd0))
  if mn > 0 and data.continuesWith("Nikon\0", mn) and mn + 18 < data.len:
    try:
      mr = tiffOf(b, mn + 10)
      let md = mr.dir(mn + 10 + mr.u32(mn + 14))
      var serial = 0
      var ver97 = 0
      var buf97: seq[uint8]
      var key = -1
      for t in md:
        case t.tag
        of 0x0c:
          if t.count == 4 and t.kind == 5:
            wb4 = [mr.num(t, 0), mr.num(t, 2), mr.num(t, 1), mr.num(t, 3)]
        of 0x1d:
          for k in 0 ..< t.count:
            let c = b.at(t.at + k)
            if c == 0: break
            serial = serial * 10 + (if c in ord('0') .. ord('9'): c - ord('0') else: c mod 10)
        of 0x3d:
          if t.count >= 4:
            for k in 0 .. 3: black4[k] = mr.num(t, k)
        of 0x96, 0x8c:
          if t.tag == 0x96 or meta < 0: meta = t.at
        of 0x97:
          for k in 0 .. 3: ver97 = ver97 * 10 + b.at(t.at + k) - ord('0')
          let q = t.at + 4
          case ver97
          of 100:
            for c in 0 .. 3: wb4[[0, 2, 1, 3][c]] = mr.u16(q + 68 + 2 * c).float
          of 102:
            for c in 0 .. 3: wb4[[0, 1, 3, 2][c]] = mr.u16(q + 6 + 2 * c).float
          of 103:
            for c in 0 .. 3: wb4[c] = mr.u16(q + 16 + 2 * c).float
          else: discard
          if ver97 >= 200:
            let q2 = q + (if ver97 != 205: 280 else: 0)
            if q2 + 324 <= b.n:
              buf97 = newSeq[uint8](324)
              for k in 0 ..< 324: buf97[k] = b.p[q2 + k]
        of 0xa7:
          key = b.at(t.at) xor b.at(t.at + 1) xor b.at(t.at + 2) xor b.at(t.at + 3)
        else: discard
      if key >= 0 and buf97.len == 324 and ver97 - 200 in 0 .. 17:
        # (the color balance is ciphered with the serial number and shutter count)
        let ci = int(nikonXlat[0][serial and 0xff])
        var cj = int(nikonXlat[1][key])
        var ck = 0x60
        for k in 0 ..< 324:
          cj = (cj + ci * ck) and 0xff
          inc ck
          buf97[k] = buf97[k] xor uint8(cj)
        let i = ord("66666>666;6A;:;555"[ver97 - 200]) - ord('0')
        for c in 0 .. 3:
          let o = (i and not 1) + c * 2
          let v = if mr.le: int(buf97[o]) or (int(buf97[o + 1]) shl 8) else: (int(buf97[o]) shl 8) or int(buf97[o + 1])
          wb4[c xor (c shr 1) xor (i and 1)] = v.float
    except RawError: discard
  # the numbers
  var curveWhite = 0.0
  if comp == 34713:
    if w * h * 3 == size * 2: result.px = packedMsb(b, at, w, h, 12)
    elif w * h * 2 == size: result.px = unpacked(b, at, w, h, false, 4)
    else:
      if at + 4 <= b.n and b.p[at] == 0xFF and b.p[at + 1] == 0x10 and b.p[at + 2] == 0xFF and b.p[at + 3] == 0x50:
        bad("a NEF of Nikon's HE compression (JPEG XS), which we do not read")
      if meta < 0: bad("a compressed NEF without its curve")
      result.px = nikonHuffman(b, mr, meta, at, at + size, w, h, bps, curveWhite)
  elif comp == 1:
    if bps == 12 and size >= (w * 12 + 7) div 8 * h and size < w * h * 2: result.px = packedMsb(b, at, w, h, 12)
    elif size >= w * h * 2: result.px = unpacked(b, at, w, h, r.le)
    else: bad("an uncompressed NEF of a kind we do not read")
  else: bad("a NEF compression we do not read (" & $comp & ")")
  # black, white
  let ab = adobeOf(result.make, result.model)
  result.colorMatrix = ab.m
  let k12 = if bps == 12: 4.0 else: 1.0
  # (black: red, green, green, blue -> each place of the mosaic)
  for k in 0 .. 3:
    let c = result.cfa[k]
    let g2 = c == 1 and result.cfa[k xor 1] == 2     # (the green in the blue row)
    let v = case c
            of 0: black4[0]
            of 2: black4[3]
            else: (if g2: black4[2] else: black4[1])
    result.black[k] = (v / k12).floor
  result.white = if bps != 12 and ab.found and ab.white > 0: ab.white.float
                 elif curveWhite > 0: curveWhite
                 else: float((1 shl bps) - 1)
  if wb4[0] > 0 and wb4[1] > 0 and wb4[2] > 0: result.wb = [wb4[0], wb4[1], wb4[2]]
  let (l, cut) = nikonVisible(result.model, w)
  result.left = l
  result.top = 0
  result.w = w - l - cut
  result.h = h

