iterator boxes(r: Rd; at, stop: int): tuple[name: string; at, stop: int] =
  ## The ISO media boxes in `at ..< stop`: each one's name and contents.
  let stop = min(stop, r.b.n)
  var o = at
  while o >= 0 and o + 8 <= stop:
    var size = r.u32(o)
    var head = 8
    if size == 1:
      if o + 16 > stop: break
      when sizeof(int) < 8:
        size = if r.u32(o + 8) != 0: high(int) else: r.u32(o + 12)
      else:
        size = (r.u32(o + 8) shl 32) or r.u32(o + 12)
      head = 16
    elif size == 0:
      size = stop - o
    if size < head or size > stop - o: break
    yield (r.b.text(o + 4, 4), o + head, o + size)
    o += size

proc child(r: Rd; at, stop: int; name: string): tuple[at, stop: int] =
  for (n, a, z) in r.boxes(at, stop):
    if n == name: return (a, z)
  (-1, -1)

type
  Cr3Track = object
    hdr: CrxHeader
    raw: bool                   ## a raw picture (its CMP1 one we read)
    meta: bool                  ## Canon's timed metadata (CTMD)
    at, size: int               ## its first sample

proc cr3Tracks(r: Rd; data: string; moovAt, moovStop: int): seq[Cr3Track] =
  ## The movie's tracks (moov/trak): their pictures' coding, and where the first is.
  for (n, a, z) in r.boxes(moovAt, moovStop):
    if n != "trak": continue
    var t: Cr3Track
    let (ma, mz) = r.child(a, z, "mdia")
    if ma >= 0:
      let (ha, hz) = r.child(ma, mz, "hdlr")
      let handler = if ha >= 0 and hz - ha >= 12: r.b.text(ha + 8, 4) else: ""
      let (ia, iz) = r.child(ma, mz, "minf")
      let (sa, sz) = if ia >= 0: r.child(ia, iz, "stbl") else: (-1, -1)
      if sa >= 0:
        for (n2, a2, z2) in r.boxes(sa, sz):
          case n2
          of "stsd":
            for (n3, a3, z3) in r.boxes(a2 + 8, z2):
              if n3 == "CTMD" and handler == "meta": t.meta = true
              if n3 != "CRAW" or handler != "vide": continue
              let (ca, cz) = r.child(a3 + 82, z3, "CMP1")
              if ca >= 0:
                try:
                  t.hdr = crxHeader(data, ca, cz - ca)
                  t.raw = true
                except RawError: discard
          of "stsz":
            if z2 - a2 >= 12:
              let fixed = r.u32(a2 + 4)
              if fixed != 0: t.size = fixed
              elif r.u32(a2 + 8) > 0 and z2 - a2 >= 16: t.size = r.u32(a2 + 12)
          of "co64":
            if z2 - a2 >= 16 and r.u32(a2 + 4) > 0:
              when sizeof(int) < 8:
                t.at = if r.u32(a2 + 8) != 0: high(int) else: r.u32(a2 + 12)
              else:
                t.at = (r.u32(a2 + 8) shl 32) or r.u32(a2 + 12)
          of "stco":
            if z2 - a2 >= 12 and r.u32(a2 + 4) > 0: t.at = r.u32(a2 + 8)
          else: discard
    result.add t

proc canonColorData(count, version: int): tuple[wb, black, black2: int] =
  ## Where a CR3 camera's ColorData (Canon's maker's note 0x4001, `count`
  ## 16-bit words, the first its `version`) has its white balance as shot
  ## and its black levels, each 4 words red, green, green, blue (0: none).
  case count
  of 1816, 1820, 1824: (0x47, 0x47 + 0x2d1, 0x47 + 0x102)          # M50, R, RP, 90D, 250D, 850D, R100, G5 X II ...
  of 1770, 2024, 3656: (0x55, 0x55 + 0x2d1, 0x55 + 0x102)          # -1D X III, R5, R6, R5's CRM
  of 3973, 3778:                                                     # R3, R6 II, R7, R8, R10, R50
    if version == 65: (0x69, 0x69 + 0x227, 0x69 + 0x116)           # (R50 V)
    else: (0x69, 0x69 + 0x213, 0x69 + 0x102)
  of 4528: (0x69, 0x69 + 0x227, 0x69 + 0x116)                       # R1, R5 II
  else: (0, 0, 0)

proc maskedBlack(s: Sensor; m03, m11, m13: int): array[4, float] =
  ## The black of each place of the mosaic from the masked columns left
  ## and right of the picture, as LibRaw finds Canon's (`m03`, `m11`,
  ## `m13`: its table's masks; 0 when nothing is known).
  let l0 = m11 + 2
  let regions = [(l0, s.left - m03 - 2), (l0 + s.left + s.w, s.rawW - m13)]
  var sum, cnt: array[4, int]
  var zero = 0
  for (x0, x1) in regions:
    for y in max(s.top, 0) ..< min(s.top + s.h, s.rawH):
      for x in max(x0, 0) ..< min(x1, s.rawW):
        let v = int(s.px[y * s.rawW + x])
        let k = (y and 1) * 2 + (x and 1)
        sum[k] += v
        inc cnt[k]
        if v == 0: inc zero
  let red = max(0, s.cfa.find(0))
  if zero < cnt[red] and cnt[0] > 0 and cnt[1] > 0 and cnt[2] > 0 and cnt[3] > 0:
    for k in 0 .. 3: result[k] = float(sum[k] div cnt[k])

const canonUuid = "\x85\xc0\xb6\x87\x82\x0f\x11\xe0\x81\x11\xf4\xce\x46\x2b\x6a\x48"

proc readCr3(data: string; b: Bytes): Sensor =
  let r = Rd(b: b, le: false)
  let (ma, mz) = r.child(0, b.n, "moov")
  if ma < 0: bad("no raw picture in the CR3")
  # Canon's box: CMT1 (IFD0: make, model), CMT3 (the maker's note)
  var cmt1, cmt3 = -1
  for (n, a, z) in r.boxes(ma, mz):
    if n == "uuid" and z - a >= 16 and b.text(a, 16) == canonUuid:
      for (n2, a2, z2) in r.boxes(a + 16, z):
        if n2 == "CMT1" and cmt1 < 0: cmt1 = a2
        elif n2 == "CMT3" and cmt3 < 0: cmt3 = a2
  # the raw: the track of the biggest picture (the first of those as big)
  let tracks = cr3Tracks(r, data, ma, mz)
  var best = -1
  var most = 0
  for i, t in tracks:
    if t.raw and t.at > 0 and t.size > 0 and t.hdr.nBits * t.hdr.width * t.hdr.height > most:
      most = t.hdr.nBits * t.hdr.width * t.hdr.height
      best = i
  if best < 0: bad("no raw picture in the CR3")
  let h = tracks[best].hdr
  result.kind = "CR3"
  result.cfaN = 2
  result.orient = 1
  if cmt1 >= 0:
    try:
      let r1 = tiffOf(b, cmt1)
      result.start(r1, r1.dir(r1.base + r1.u32(r1.base + 4)), "CR3")
    except RawError: discard
  result.px = decodeCrx(data, h, tracks[best].at, tracks[best].size)
  result.rawW = h.width
  result.rawH = h.height
  result.cfa = case h.cfaLayout
               of 1: @[1, 0, 2, 1]
               of 2: @[1, 2, 0, 1]
               of 3: @[2, 1, 1, 0]
               else: @[0, 1, 1, 2]
  # the maker's notes (CMT3, and in the first CTMD sample's records of
  # kinds 7 and 8): the sensor's parts, white balance, black
  var notes: seq[int]
  if cmt3 >= 0: notes.add cmt3
  for t in tracks:
    if not t.meta or t.at <= 0: continue
    let le = Rd(b: b, le: true)
    var o = 0
    while o + 6 < t.size and t.at + o + 6 <= b.n:
      let size = le.u32(t.at + o)
      let kind = le.u16(t.at + o + 4)
      if size < 1 or o + size > t.size: break
      if kind in [7, 8]:
        var q = o + 12
        while q + 8 < o + size and t.at + q + 8 <= b.n:
          let n = le.u32(t.at + q)
          if n < 8 or q + n > o + size: break
          if le.u32(t.at + q + 4) == 0x927c: notes.add t.at + q + 8
          q += n
      o += size
    break
  var crop = [-1, -1, -1, -1]
  var sensorW, sensorH = 0
  var wb4: array[4, float]
  var black4: array[4, int]                  # red, green, blue, the other green
  for note in notes:
    try:
      let r3 = tiffOf(b, note)
      for t in r3.dir(r3.base + r3.u32(r3.base + 4)):
        if t.tag == 0xe0 and t.count >= 9:
          sensorW = int(r3.num(t, 1))
          sensorH = int(r3.num(t, 2))
          for k in 0 .. 3: crop[k] = int(r3.num(t, 5 + k))
        elif t.tag == 0x4001 and t.count > 500:
          let (wbAt, blackAt, black2At) = canonColorData(t.count, int(r3.num(t, 0)))
          if wbAt > 0 and wbAt + 4 <= t.count:
            for c in 0 .. 3: wb4[[0, 1, 3, 2][c]] = r3.num(t, wbAt + c)
          for at in [blackAt, black2At]:
            if at > 0 and at + 4 <= t.count and black4 == [0, 0, 0, 0]:
              for c in 0 .. 3: black4[[0, 1, 3, 2][c]] = int(r3.num(t, at + c))
              if (black4[0] + black4[1] + black4[2] + black4[3]) div 4 == 0: black4 = [0, 0, 0, 0]
    except RawError: discard
  # the picture's part and black: as dcraw and LibRaw know Canon's sensors
  # (black from the masked columns beside the picture), else as the camera says
  var known = false
  for t in canonSensors:
    if t[0] == result.rawW and t[1] == result.rawH:
      result.left = t[2]
      result.top = t[3]
      result.w = result.rawW - t[2] - t[4]
      result.h = result.rawH - t[3] - t[5]
      if t[10] == 0x49: result.cfa = @[1, 2, 0, 1]
      result.black = maskedBlack(result, t[7], t[8], t[9])
      known = true
      break
  if not known:
    result.left = 0
    result.top = 0
    result.w = result.rawW
    result.h = result.rawH
    if black4 != [0, 0, 0, 0]:
      const places = [[0, 1, 3, 2], [1, 0, 2, 3], [3, 2, 0, 1], [2, 3, 1, 0]]   # (LibRaw's colors of the places)
      for k in 0 .. 3: result.black[k] = float(black4[places[h.cfaLayout and 3][k]])
      if sensorW == result.rawW and sensorH == result.rawH:
        let l = (crop[0] + 1) and not 1
        let tp = (crop[1] + 1) and not 1
        if l >= 0 and tp >= 0 and crop[2] > l and crop[3] > tp and crop[2] <= result.rawW and crop[3] <= result.rawH:
          result.left = l
          result.top = tp
          result.w = crop[2] - l
          result.h = crop[3] - tp
    else:
      result.black = maskedBlack(result, 0, 0, 0)
  result.white = float((1 shl h.nBits) - 1)
  result.colorMatrix = adobeOf(result.make, result.model).m
  if wb4[0] > 0 and wb4[1] > 0 and wb4[2] > 0: result.wb = [wb4[0], wb4[1], wb4[2]]

# ---- Olympus ORF -----------------------------------------------------------------------------------------------

type
  OlyPump = object
    ## Olympus's bits: big-endian words, taken from the top.
    b: Bytes
    pos: int
    store: uint32
    count: uint32

proc get2(o: var OlyPump): uint32 {.inline.} =
  var v = 0'u32
  for k in 0 .. 1:
    v = (v shl 8) or (if o.pos < o.b.n: uint32(o.b.p[o.pos]) else: 0'u32)
    inc o.pos
  v

proc replaceData(o: var OlyPump) {.inline.} =
  var v = 0'u32
  for k in 0 .. 3:
    v = (v shl 8) or (if o.pos < o.b.n: uint32(o.b.p[o.pos]) else: 0'u32)
    inc o.pos
  o.store = v
  o.count = 32

proc addData(o: var OlyPump): uint32 {.inline.} =
  o.store = (o.store shl 16) or o.get2()
  o.count += 16
  o.count

template shl32(v: uint32; n: uint32): uint32 =
  ## A shift by 32 is none (as the machine does it).
  (v shl (n and 31))

proc getbits(o: var OlyPump; w: uint32): uint32 {.inline.} =
  while o.count < w: discard o.addData()
  result = shl32(o.store, 32'u32 - (o.count and 0x1f)) shr (32'u32 - w)
  o.count -= w

proc skipBit(o: var OlyPump; vbits: var uint32) {.inline.} =
  if vbits == 0:
    o.replaceData()
    dec o.count
    vbits = o.count
  else:
    dec vbits
    o.count = vbits

proc olyCode(o: var OlyPump; wbits, t640, t643, t652: uint32; glc, t640bits, t643bits: var int): int {.inline.} =
  if o.count == 0: o.replaceData()
  dec o.count
  let highbit = int((o.store shr o.count) and 1)
  t643bits = if t643 > 0: int(o.getbits(t643)) else: 0
  t640bits = if t640 > 0: int(o.getbits(t640)) else: 0
  var vbits = o.count
  var high = 0'u32
  var low = 0'u32
  while true:
    o.skipBit(vbits)
    if ((o.store shr vbits) and 1) != 0: break
    inc high
    if t652 == high:
      high = 0
      if wbits != 15:
        let i = 15'u32 - wbits
        while vbits < i: vbits = o.addData()
        high = shl32(o.store, 32'u32 - (vbits and 0x1f)) shr (wbits + 17)
        vbits -= i
        o.count = vbits
      o.skipBit(vbits)
      break
  if wbits >= 1:
    while vbits < wbits: vbits = o.addData()
    low = shl32(o.store, 32'u32 - (vbits and 0x1f)) shr (32'u32 - (wbits and 0x1f))
    o.count = vbits - wbits
  glc = int(low or (high shl wbits))
  if highbit == 1: not glc else: glc

proc olympusCompressed(b: Bytes; at, w, h: int; t: array[14, int]): seq[uint16] =
  ## Olympus's compressed numbers (LibRaw's reading of them): each a
  ## difference from a guess of its color's neighbors, in an adaptive code
  ## whose parameters the maker's note (0x640 ..) gives.
  # the header: `t[13]` bytes making 1, then two zeros
  var q = at
  var v = 0
  for k in 0 ..< t[13]:
    v = (v shl 8) or b.at(q)
    inc q
  if t[13] <= 0 or v != 1 or b.at(q) != 0 or b.at(q + 1) != 0: bad("an ORF of a kind we do not read")
  q += 2
  let t640 = t[0]
  let t643 = t[3]
  let shl641 = 1 shl t[1]
  let t642 = t[2]
  let t644 = t[4]
  let shl645 = 1 shl (t[5] and 0x1f)
  let (t646, t647, t648, t649, t650, t651) = (t[6], t[7], t[8], t[9], t[10], t[11])
  let t652 = max(1, t[12])
  var bitcounts = newSeq[int](65536)
  var n = 1
  for i in 0 .. 15:
    for _ in 0 ..< (1 shl i):
      bitcounts[n] = i + 1
      inc n
      if n >= 65536: break
  result = newSeq[uint16](w * h)
  let rp = uptr(result)
  var o = OlyPump(b: b, pos: q)
  var context: array[4, int]
  var lpred, pred1, glc, gcode = 0
  for row in 0 ..< h:
    for col in 0 ..< w:
      var wbits, vbits, t640bits, t643bits: int
      let p = gcode
      gcode = glc
      let psel = if col > 1 and shl645 >= p: context[3] + 1 else: 0
      context[3] = context[2]
      context[2] = psel
      if col > 1:
        let hb = bitcounts[p and 0xffff]
        let t1 = if psel >= t646: t648 else: t650
        let t2 = if psel >= t646: t647 else: t649
        wbits = t2 + max(hb - t1, -1) + 1
      else:
        wbits = t649
      if wbits > t651: wbits = t651
      if wbits >= 16 or wbits < 0: bad("a damaged ORF")
      var code = o.olyCode(uint32(wbits), uint32(t640), uint32(t643), uint32(t652), glc, t640bits, t643bits)
      if t643 != 0:
        let vv = if col < 2: 0 else: pred1
        if t643 == 1:
          code = t643bits + 2 * (vv + code)
          vbits = vv + (code shr 1)
        else:
          code = t643bits + 4 * (vv + code)
          vbits = ((code shr 1) and not 1) + vv + (code shr 2)
      else:
        vbits = 0
      pred1 = context[0]
      context[0] = if t644 == 15: 0 else: vbits shr t644
      let west = if col < 2: t642 else: context[1]
      var north = if row < 2: t642 else: int(rp[(row - 2) * w + col]) shr t640
      let nw = if row < 2 or col < 2: t642 else: int(rp[(row - 2) * w + col - 2]) shr t640
      context[1] = lpred
      if west < north or nw < west:
        if nw <= north and west >= north: north = west
        elif nw < north or west >= north:
          if nw > west or west >= north:
            if abs(north - nw) > shl641: north += west - nw
            elif abs(west - nw) <= shl641: north = (north + west) shr 1
            else: north = north + west - nw
        else: north = west
      lpred = code + north
      rp[row * w + col] = uint16((t640bits + ((code + north) shl t640)) and 0xFFFF)

proc subDir(r: Rd; d: Dir; tag: int): Dir =
  ## The directory a tag points to (its offset counted from `r.base`).
  let k = d.find(tag)
  if k < 0: return
  try: r.dir(r.base + r.u32(d[k].at)) except RawError: @[]

proc exifCfa(r: Rd; exif: Dir): seq[int] =
  ## EXIF's CFAPattern (2 x 2 only).
  let k = exif.find(0xa302)
  if k < 0 or exif[k].count < 8: return
  let at = exif[k].at
  if r.u16(at) == 2 and r.u16(at + 2) == 2:
    for i in 0 .. 3:
      let c = r.b.at(at + 4 + i)
      if c > 2: result = @[]; return
      result.add c
  elif r.u16(at) == 0x200 and r.u16(at + 2) == 0x200:
    # (written in the other byte order)
    for i in 0 .. 3:
      let c = r.b.at(at + 4 + i)
      if c > 2: result = @[]; return
      result.add c

proc readOrf(data: string; b: Bytes): Sensor =
  let r = Rd(b: b, le: data[0] == 'I', base: 0)
  let first = r.u32(4)
  let ifd0 = r.dir(first)
  result.start(r, ifd0, "ORF")
  let dirs = r.dirsFrom(first)
  var raw: Dir
  var best = 0
  for d in dirs:
    let a = int(r.get(d, 256)) * int(r.get(d, 257))
    if a > best and r.nums(d, 273).len > 0:
      best = a
      raw = d
  if best == 0: bad("no raw picture in the ORF")
  let w = int(r.get(raw, 256))
  let h0 = int(r.get(raw, 257))
  let h = h0 + (h0 and 1)       # (as dcraw: whole 2 x 2s)
  var bps = int(r.get(raw, 258, 12))
  let (at, size) = r.stripsOf(raw)
  result.rawW = w
  result.rawH = h
  let exif = r.exifDir(ifd0)
  let ecfa = r.exifCfa(exif)
  result.cfa = if ecfa.len == 4: ecfa else: @[0, 1, 1, 2]
  # the maker's note
  var wb = [0.0, 0.0, 0.0]
  var black4 = [0.0, 0.0, 0.0, 0.0]
  var crop = [-1, -1, -1, -1]
  var validBits = 0
  var t: array[14, int]
  let (mn, _) = r.makerNote(exif)
  if mn > 0:
    try:
      var mr: Rd
      var md: Dir
      if data.continuesWith("OLYMPUS\0", mn) or data.continuesWith("OM SYS", mn):
        let o = if data[mn + 1] == 'M': mn + 12 else: mn + 8
        mr = Rd(b: b, le: data[o] == 'I', base: mn)
        md = mr.dir(o + 4)
      elif data.continuesWith("OLYMP\0", mn):
        mr = r
        md = r.dir(mn + 8)
      for tg in md:
        case tg.tag
        of 0x1017: wb[0] = mr.num(tg) / 256
        of 0x1018: wb[2] = mr.num(tg) / 256
        of 0x1012:
          if tg.count == 4:
            for c in 0 .. 3: black4[c] = mr.num(tg, c)
        else: discard
      let ip = mr.subDir(md, 0x2040)
      for tg in ip:
        case tg.tag
        of 0x0100:
          if tg.count >= 2:
            wb[0] = mr.num(tg, 0) / 256
            wb[2] = mr.num(tg, 1) / 256
        of 0x0600:
          if tg.count >= 4:
            for c in 0 .. 3: black4[c] = mr.num(tg, c)
        of 0x0611: validBits = int(mr.num(tg))
        of 0x0612 .. 0x0615: crop[tg.tag - 0x0612] = int(mr.num(tg))
        of 0x0640 .. 0x0649: t[tg.tag - 0x0640] = int(mr.num(tg))
        of 0x0650 .. 0x0653: t[tg.tag - 0x0650 + 10] = int(mr.num(tg))   # (0x640 .. 0x653 read as decimal)
        else: discard
    except RawError: discard
  if wb[0] > 0 and wb[2] > 0: wb[1] = 1
  # the numbers
  let offs = r.nums(raw, 273)
  let cnts = r.nums(raw, 279)
  let rowBytes = w * 12 div 8
  var short = -1
  for k in 0 ..< offs.len - 1:
    if k < cnts.len and int(cnts[k]) < int(cnts[0]): short = k
  if bps == 12 and size * 2 == w * (h - (h0 and 1)) * 3 and short >= 0 and (w * 12) mod 32 == 0:
    # (older cameras: the even rows, then the odd rows)
    result.px = newSeq[uint16](w * h)
    var irow = 0
    let half = (h + 1) shr 1
    for k in 0 ..< min(offs.len, cnts.len):
      let rows = int(cnts[k]) div rowBytes
      if k == short + 1: irow = half
      let part = packedMsb(b, int(offs[k]), w, rows, 12)
      for y in 0 ..< rows:
        let row = if irow < half: irow * 2 else: (irow - half) * 2 + 1
        if row < h:
          for x in 0 ..< w: result.px[row * w + x] = part[y * w + x]
        inc irow
  elif bps == 12 and size >= (w * 12 + 7) div 8 * h0:
    result.px = packedMsb(b, at, w, h0, 12)
    result.px.setLen(w * h)
  elif bps in [14, 16] and size * 7 > w * h and size < w * h * 2:
    result.px = olympusCompressed(b, at, w, h, t)
    bps = 12
  elif size >= w * h * 2: result.px = unpacked(b, at, w, h, r.le, 4)
  else: bad("an ORF of a kind we do not read")
  if validBits in 10 .. 16: bps = validBits
  let ab = adobeOf(result.make, result.model)
  result.colorMatrix = ab.m
  for k in 0 .. 3:
    let c = result.cfa[k]
    result.black[k] = case c
                      of 0: black4[0]
                      of 2: black4[3]
                      else: (if result.cfa[k xor 1] == 2: black4[2] else: black4[1])
  if bps == 14:
    for v in result.black.mitems: v *= 4
  result.white = if ab.found and ab.white > 0: ab.white.float else: float((1 shl bps) - 1)
  if wb[0] > 0 and wb[2] > 0: result.wb = wb
  # the picture's part
  result.left = 0
  result.top = 0
  result.w = w
  result.h = h0
  if crop[2] > 0 and crop[3] > 0 and crop[0] >= 0 and crop[1] >= 0 and crop[0] + crop[2] <= w and crop[1] + crop[3] <= h:
    result.left = crop[0]
    result.top = crop[1]
    result.w = crop[2]
    result.h = crop[3]
  else:
    case w
    of 4100: result.w -= 4
    of 4080: result.w -= 24
    of 10400: result.w -= 12
    of 8200: result.w -= 30
    of 8180: result.w -= 10
    of 9280:
      result.w -= 6
      result.h -= 6
    else: discard

# ---- Panasonic RW2 ---------------------------------------------------------------------------------------------

proc panasonicClassic(b: Bytes; at, w, h: int; split = 0x2008): seq[uint16] =
  ## Panasonic's compressed numbers: blocks of 14 (two colors), each a base
  ## and 8-bit steps of a shared scale, the bits read backwards in blocks
  ## of 16 bytes of 16 KB.
  result = newSeq[uint16](w * h)
  var buf: array[0x4002, uint8]
  var vpos = 0
  var fpos = at
  var pred, nonz: array[2, int]
  var sh = 0
  template data(nb: int): int =
    if vpos == 0:
      for k in 0 ..< 0x4000 - split:
        buf[split + k] = (if fpos + k < b.n: b.p[fpos + k] else: 0'u8)
      for k in 0 ..< split:
        buf[k] = (if fpos + 0x4000 - split + k < b.n: b.p[fpos + 0x4000 - split + k] else: 0'u8)
      fpos += 0x4000
    vpos = (vpos - nb) and 0x1ffff
    let byt = (vpos shr 3) xor 0x3ff0
    ((int(buf[byt]) or (int(buf[byt + 1]) shl 8)) shr (vpos and 7)) and ((1 shl nb) - 1)
  for row in 0 ..< h:
    for col in 0 ..< w:
      let i = col mod 14
      if i == 0:
        pred = [0, 0]
        nonz = [0, 0]
      if i mod 3 == 2: sh = 4 shr (3 - data(2))
      if nonz[i and 1] != 0:
        let j = data(8)
        if j != 0:
          pred[i and 1] -= 0x80 shl sh
          if pred[i and 1] < 0 or sh == 4: pred[i and 1] = pred[i and 1] and ((1 shl sh) - 1)
          pred[i and 1] += j shl sh
      else:
        nonz[i and 1] = data(8)
        if nonz[i and 1] != 0 or i > 11:
          pred[i and 1] = (nonz[i and 1] shl 4) or data(4)
      result[row * w + col] = uint16(pred[col and 1] and 0xFFFF)

proc panasonicV5(b: Bytes; at, w, h, bps: int): seq[uint16] =
  ## Panasonic's packed numbers (RawFormat 5): 10 of 12 bits or 9 of 14 bits
  ## in each 16 bytes, the 16 KB blocks turned as in the older format.
  result = newSeq[uint16](w * h)
  let per = if bps == 12: 10 else: 9
  var buf: array[0x4000, uint8]
  var vpos = 0
  var fpos = at
  var bytes: array[16, int]
  let split = 0x2008
  for row in 0 ..< h:
    var col = 0
    while col < w:
      for k in 0 .. 15:
        if vpos == 0:
          for q in 0 ..< 0x4000 - split:
            buf[split + q] = (if fpos + q < b.n: b.p[fpos + q] else: 0'u8)
          for q in 0 ..< split:
            buf[q] = (if fpos + 0x4000 - split + q < b.n: b.p[fpos + 0x4000 - split + q] else: 0'u8)
          fpos += 0x4000
        bytes[k] = int(buf[vpos])
        vpos = (vpos + 1) and 0x3FFF
      var v: array[10, int]
      if bps == 12:
        for k in 0 .. 4:
          v[2 * k] = ((bytes[3 * k + 1] and 0xF) shl 8) + bytes[3 * k]
          v[2 * k + 1] = 16 * bytes[3 * k + 2] + (bytes[3 * k + 1] shr 4)
      else:
        v[0] = bytes[0] + ((bytes[1] and 0x3F) shl 8)
        v[1] = (bytes[1] shr 6) + 4 * bytes[2] + ((bytes[3] and 0xF) shl 10)
        v[2] = (bytes[3] shr 4) + 16 * bytes[4] + ((bytes[5] and 3) shl 12)
        v[3] = ((bytes[5] and 0xFC) shr 2) + (bytes[6] shl 6)
        v[4] = bytes[7] + ((bytes[8] and 0x3F) shl 8)
        v[5] = (bytes[8] shr 6) + 4 * bytes[9] + ((bytes[10] and 0xF) shl 10)
        v[6] = (bytes[10] shr 4) + 16 * bytes[11] + ((bytes[12] and 3) shl 12)
        v[7] = ((bytes[12] and 0xFC) shr 2) + (bytes[13] shl 6)
        v[8] = bytes[14] + ((bytes[15] and 0x3F) shl 8)
      for k in 0 ..< per:
        if col + k < w: result[row * w + col + k] = uint16(v[k] and 0xFFFF)
      col += per

proc readRw2(data: string; b: Bytes): Sensor =
  let r = Rd(b: b, le: true, base: 0)
  let first = r.u32(4)
  let ifd0 = r.dir(first)
  result.kind = "RW2"
  result.make = r.str(ifd0, 0x10f)
  result.model = r.str(ifd0, 0x110)
  result.orient = int(r.get(ifd0, 0x112, 1))
  result.cfaN = 2
  let w = int(r.get(ifd0, 2))
  let h = int(r.get(ifd0, 3))
  if w <= 0 or h <= 0: bad("a damaged RW2")
  result.rawW = w
  result.rawH = h
  let bps = int(r.get(ifd0, 0x0a, 12))
  let encoding = int(r.get(ifd0, 0x2d, 4))
  var at = int(r.get(ifd0, 0x118, 0))
  if at == 0: at = int(r.get(ifd0, 0x111, 0))
  if at <= 0 or at >= b.n: bad("an RW2 without its data")
  case encoding
  of 5: result.px = panasonicV5(b, at, w, h, bps)
  of 6, 7, 8: bad("an RW2 of a kind we do not read yet (RawFormat " & $encoding & ")")
  else:
    if (b.n - at) >= w * h * 2 and (b.n - at) div (w * 8 div 7) != h: result.px = unpacked(b, at, w, h, true, 4)
    else: result.px = panasonicClassic(b, at, w, h)
  # the mosaic: tag 9, 1 .. 4 (from the numbers' top left)
  let pat = int(r.get(ifd0, 9, 1))
  result.cfa = case pat
               of 2: @[1, 0, 2, 1]
               of 3: @[1, 2, 0, 1]
               of 4: @[2, 1, 1, 0]
               else: @[0, 1, 1, 2]
  # black, white, white balance
  let add = if encoding == 4: 15.0 else: 0.0
  let br = r.get(ifd0, 0x1c, -1)
  let bg = r.get(ifd0, 0x1d, -1)
  let bb = r.get(ifd0, 0x1e, -1)
  let ab = adobeOf(result.make, result.model)
  result.colorMatrix = ab.m
  if br >= 0 and bg >= 0 and bb >= 0 and (br > 0 or bg > 0 or bb > 0):
    for k in 0 .. 3:
      result.black[k] = (case result.cfa[k]
                         of 0: br
                         of 2: bb
                         else: bg) + add
  else:
    for k in 0 .. 3: result.black[k] = float(abs(ab.black))
  result.white = if ab.found and ab.white > 0: ab.white.float else: float((1 shl bps) - 1)
  let wr = r.get(ifd0, 0x24)
  let wg = r.get(ifd0, 0x25)
  let wbl = r.get(ifd0, 0x26)
  if wr > 0 and wg > 0 and wbl > 0: result.wb = [wr, wg, wbl]
  elif r.get(ifd0, 0x11) > 0 and r.get(ifd0, 0x12) > 0: result.wb = [r.get(ifd0, 0x11), 256.0, r.get(ifd0, 0x12)]
  # the picture's part: the sensor's borders
  let top = int(r.get(ifd0, 4))
  let left = int(r.get(ifd0, 5))
  let bottom = int(r.get(ifd0, 6))
  let right = int(r.get(ifd0, 7))
  if right > left and bottom > top and right <= w and bottom <= h:
    result.left = left
    result.top = top
    result.w = right - left
    result.h = bottom - top
  else:
    result.left = 0
    result.top = 0
    result.w = w
    result.h = h

