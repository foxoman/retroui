proc packed12Lsb(b: Bytes; at, w, h: int): seq[uint16] =
  ## 12 bits a number, least significant first: two in three bytes.
  if at < 0 or at + (w * h * 3 + 1) div 2 > b.n: bad("the file ends early")
  result = newSeq[uint16](w * h)
  let rp = uptr(result)
  let p = b.p
  let pairs = w * h div 2
  parallelChunks(pairs, lo, hi):
    for i in lo ..< hi:
      let q = at + 3 * i
      let b0 = int(p[q])
      let b1 = int(p[q + 1])
      let b2 = int(p[q + 2])
      rp[2 * i] = uint16(b0 or ((b1 and 15) shl 8))
      rp[2 * i + 1] = uint16((b1 shr 4) or (b2 shl 4))

proc jpegOrientation(r: Rd; at: int): int =
  ## The orientation in a JPEG's EXIF (1: none found).
  result = 1
  var q = at + 2
  for _ in 0 .. 8:
    if q + 10 > r.b.n or r.b.p[q] != 0xFF: return
    let m = int(r.b.p[q + 1])
    let len = (int(r.b.p[q + 2]) shl 8) or int(r.b.p[q + 3])
    if m == 0xE1 and r.b.text(q + 4, 6) == "Exif\0\0":
      try:
        let t = tiffOf(r.b, q + 10)
        let d = t.dir(t.base + t.u32(t.base + 4))
        return int(t.get(d, 274, 1))
      except RawError: return
    if m == 0xDA: return
    q += 2 + len

proc readRaf(data: string; b: Bytes): Sensor =
  let be = Rd(b: b, le: false, base: 0)
  result.kind = "RAF"
  result.make = "FUJIFILM"
  result.model = b.text(0x1c, 0x20).split('\0')[0].strip()
  result.orient = jpegOrientation(be, be.u32(84))
  let meta = be.u32(92)
  let co = be.u32(100)
  let cl = be.u32(104)
  if co <= 0 or co >= b.n: bad("a damaged RAF")
  # the records: sizes, crop, mosaic, white balance
  var rawW, rawH, cropT, cropL, cropW, cropH = 0
  var xtrans: seq[int]
  var wb: array[3, float]
  var layout = 8
  var black = 0.0
  var bps = 0
  let n = be.u32(meta)
  var q = meta + 4
  for _ in 0 ..< min(n, 256):
    let tag = be.u16(q)
    let len = be.u16(q + 2)
    let v = q + 4
    case tag
    of 0x100:
      rawH = be.u16(v)
      rawW = be.u16(v + 2)
    of 0x110:
      cropT = be.u16(v)
      cropL = be.u16(v + 2)
    of 0x111:
      cropH = be.u16(v)
      cropW = be.u16(v + 2)
    of 0x130:
      layout = b.at(v + 1)
    of 0x131:
      if len >= 36:
        xtrans = newSeq[int](36)
        for c in 0 ..< 36: xtrans[35 - c] = clamp(b.at(v + c), 0, 2)
    of 0x2ff0:
      if len >= 8: wb = [be.u16(v + 2).float, be.u16(v).float, be.u16(v + 6).float]
    else: discard
    q = v + len
  # the numbers: in a TIFF of Fujifilm's tags, or straight after
  var at = co
  var size = cl
  if data.continuesWith("II*\0", co) or data.continuesWith("MM\0*", co):
    let t = tiffOf(b, co)
    let d0 = t.dir(co + t.u32(co + 4))
    let fd = t.subDir(d0, 0xf000)
    if fd.len > 0:
      rawW = int(t.get(fd, 0xf001, rawW.float))
      rawH = int(t.get(fd, 0xf002, rawH.float))
      bps = int(t.get(fd, 0xf003, 0))
      at = co + int(t.get(fd, 0xf007, 0))
      size = int(t.get(fd, 0xf008, 0))
      black = t.get(fd, 0xf00a, 0)
      let k = fd.find(0xf00e)
      if k >= 0 and fd[k].count >= 3:
        wb = [t.num(fd[k], 1), t.num(fd[k], 0), t.num(fd[k], 2)]
  let w = rawW
  let h = rawH
  if w <= 0 or h <= 0 or w * h > 200_000_000: bad("a damaged RAF")
  if (layout and 8) == 0: bad("a Fujifilm SuperCCD RAF (its pixels turned 45 degrees), which we do not read")
  if size >= w * h * 2: result.px = unpacked(b, at, w, h, true)
  elif size * 2 == w * h * 3: result.px = packed12Lsb(b, at, w, h)
  else: bad("a compressed RAF, which we do not read yet")
  if bps == 0: bps = 14
  result.rawW = w
  result.rawH = h
  if xtrans.len == 36:
    result.cfaN = 6
    result.cfa = xtrans
  else:
    result.cfaN = 2
    result.cfa = @[0, 1, 1, 2]
  for k in 0 .. 3: result.black[k] = black
  let ab = adobeOf(result.make, result.model)
  result.colorMatrix = ab.m
  result.white = if ab.found and ab.white > 0: ab.white.float else: float((1 shl bps) - 1)
  if wb[0] > 0 and wb[1] > 0 and wb[2] > 0: result.wb = wb
  # the picture's part: the camera's crop
  if cropW > 0 and cropH > 0 and cropL + cropW <= w and cropT + cropH <= h:
    result.left = cropL
    result.top = cropT
    result.w = cropW
    result.h = cropH
  else:
    result.left = 0
    result.top = 0
    result.w = w
    result.h = h

# ---- all together ------------------------------------------------------------------------------------------------

proc readSensor*(data: string): Sensor =
  ## The sensor's numbers of a camera's raw file, and what they mean.
  ## Raises `RawError` when it is not one we read.
  let b = bytesOf(data)
  case rawKind(data)
  of "NEF": readNef(data, b)
  of "ARW": readArw(data, b)
  of "CR2": readCr2(data, b)
  of "ORF": readOrf(data, b)
  of "RW2": readRw2(data, b)
  of "PEF": readPef(data, b)
  of "RAF": readRaf(data, b)
  of "CR3": readCr3(data, b)
  of "DNG": bad("a DNG: rawphoto's readDng reads it")
  else: bad("not a raw file we know")

proc readCameraRaw*(data: string): RawImage =
  ## A camera's raw file (not a DNG) as light: `develop(readSensor(data))`.
  develop(readSensor(data))

cameraRawReader = readCameraRaw
