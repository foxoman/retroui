proc makeOf(make: string): string =
  let m = make.toLowerAscii
  if m.startsWith("nikon"): "Nikon"
  elif m.startsWith("canon"): "Canon"
  elif m.startsWith("sony"): "Sony"
  elif m.startsWith("fuji"): "Fujifilm"
  elif m.startsWith("olympus") or m.startsWith("om digital"): "Olympus"
  elif m.startsWith("panasonic") or m.startsWith("leica"): "Panasonic"
  elif m.startsWith("pentax") or m.startsWith("ricoh"): "Pentax"
  else: make

proc adobeOf(make, model: string): tuple[found: bool; black, white: int; m: array[9, float]] =
  ## The model's matrix (XYZ to camera, as Adobe's DNG converter has it),
  ## and its table's black and white; not found: the average of its
  ## maker's (or of all).
  let mk = makeOf(make)
  let md = normalModel(mk, model).toLowerAscii
  for (tm, prefix, bl, wh, t) in adobe:
    if tm == mk and md.startsWith(prefix.toLowerAscii):
      for i in 0 .. 8: result.m[i] = t[i].float / 10000
      result = (true, bl, wh, result.m); return
  var n = 0
  for (tm, prefix, bl, wh, t) in adobe:
    if tm == mk:
      for i in 0 .. 8: result.m[i] += t[i].float / 10000
      inc n
  if n == 0:
    for (tm, prefix, bl, wh, t) in adobe:
      for i in 0 .. 8: result.m[i] += t[i].float / 10000
      inc n
  for i in 0 .. 8: result.m[i] /= n.float

