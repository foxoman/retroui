proc tiffMake(b: Bytes): string =
  try:
    let r = tiffOf(b)
    let d = r.dir(r.base + r.u32(4))
    r.str(d, 271)
  except RawError: ""

proc dngVersion(b: Bytes): bool =
  ## IFD0 has a DNGVersion.
  try:
    let r = tiffOf(b)
    r.dir(r.base + r.u32(4)).find(50706) >= 0
  except RawError: false

proc rawKind*(data: string): string =
  ## What kind of raw photo the bytes are: "NEF", "ARW", "CR2", "CR3",
  ## "RAF", "ORF", "RW2", "PEF", "DNG", or "" (none we know).
  let b = bytesOf(data)
  if data.len < 16: return ""
  if data.startsWith("FUJIFILMCCD-RAW"): return "RAF"
  if data[4 .. 7] == "ftyp" and data[8 .. 11] == "crx ": return "CR3"
  if data.startsWith("IIRO") or data.startsWith("IIRS") or data.startsWith("MMOR"): return "ORF"
  if data.startsWith("IIU\0"): return "RW2"
  if not (data.startsWith("II*\0") or data.startsWith("MM\0*")): return ""
  if dngVersion(b): return "DNG"
  if data.startsWith("II*\0") and data[8 .. 9] == "CR": return "CR2"
  let mk = tiffMake(b).toLowerAscii
  if mk.startsWith("nikon"): "NEF"
  elif mk.startsWith("sony"): "ARW"
  elif mk.startsWith("canon"): "CR2"
  elif mk.startsWith("pentax") or mk.startsWith("ricoh") or mk.startsWith("asahi"): "PEF"
  elif mk.startsWith("olympus") or mk.startsWith("om digital"): "ORF"
  elif mk.startsWith("panasonic") or mk.startsWith("leica"): "RW2"
  else: ""

proc isRaw*(data: string): bool =
  ## The bytes are a raw photo of a kind we know (see `rawKind`).
  rawKind(data) != ""

