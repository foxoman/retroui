proc mosaicDir(r: Rd; dirs: seq[Dir]; photometric = 32803): Dir =
  ## The biggest picture of the sensor's numbers.
  var best = 0
  for d in dirs:
    let w = int(r.get(d, 256))
    let h = int(r.get(d, 257))
    if (photometric == 0 or int(r.get(d, 262)) == photometric) and int(r.get(d, 277, 1)) == 1 and w * h > best:
      best = w * h
      result = d
  if best == 0: bad("no raw picture in the file")

proc stripsOf(r: Rd; d: Dir): tuple[at, len: int] =
  ## Where the picture's strips are (one after the other), and how long.
  let offs = r.nums(d, 273)
  let cnts = r.nums(d, 279)
  if offs.len == 0: bad("a raw picture without its data")
  result.at = int(offs[0])
  for c in cnts: result.len += int(c)

proc cfaOf(s: var Sensor; r: Rd; d: Dir; default: array[4, int]) =
  ## The 2 x 2 mosaic's colors from its directory's CFAPattern.
  s.cfa = @default
  let dim = r.nums(d, 33421)
  let pat = r.nums(d, 33422)
  if (dim.len == 0 or (dim.len == 2 and dim[0] == 2 and dim[1] == 2)) and pat.len == 4:
    var ok = true
    for v in pat:
      if v notin [0.0, 1.0, 2.0]: ok = false
    if ok:
      for k in 0 .. 3: s.cfa[k] = int(pat[k])

proc unpacked(b: Bytes; at, w, h: int; le: bool; shift = 0): seq[uint16] =
  ## Two bytes a number.
  if at < 0 or at + w * h * 2 > b.n: bad("the file ends early")
  result = newSeq[uint16](w * h)
  let rp = uptr(result)
  let p = b.p
  parallelRows(h, y):
    for x in 0 ..< w:
      let i = at + (y * w + x) * 2
      let v = if le: int(p[i]) or (int(p[i + 1]) shl 8) else: (int(p[i]) shl 8) or int(p[i + 1])
      rp[y * w + x] = uint16(v shr shift)

proc packedMsb(b: Bytes; at, w, h, bps: int): seq[uint16] =
  ## `bps` bits a number, most significant first; each row starts on a byte.
  let row = (w * bps + 7) div 8
  if at < 0 or at + row * h > b.n: bad("the file ends early")
  result = newSeq[uint16](w * h)
  let rp = uptr(result)
  let p = b.p
  parallelRows(h, y):
    var pos = at + y * row
    var acc = 0'u64
    var n = 0
    for x in 0 ..< w:
      while n < bps:
        acc = (acc shl 8) or uint64(p[pos])
        inc pos
        n += 8
      rp[y * w + x] = uint16((acc shr (n - bps)) and ((1'u64 shl bps) - 1))
      n -= bps

