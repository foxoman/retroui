## Cameras' own raw files, besides DNG: Nikon NEF, Sony ARW, Canon CR2 and
## CR3, Olympus ORF, Panasonic RW2, Pentax PEF and Fujifilm RAF. The sensor's
## numbers are read as the camera wrote them (`readSensor`: the same
## numbers LibRaw reads), with what they mean -- black and white levels,
## the color mosaic, the picture's part of the sensor, the white balance as
## shot, the camera's colors (Adobe's matrix of its model, as dcraw and
## LibRaw tabulate them) -- and then made light as rawphoto makes a DNG's
## (`develop`, `readRaw`), for rawphoto's `developRaw` and `docOfRaw`.
##
## ```nim
## import retroui/[rawformats, photodevelop]
## let data = readFile("DSC_0042.NEF")
## if isRaw(data):
##   echo rawKind(data)                       # "NEF"
##   let raw = readRaw(data)                  # linear sRGB light
##   let img = developRaw(raw, Develop(exposure: 30))
## ```
##
## Importing this module anywhere also makes rawphoto's `readRaw` read
## these kinds. A CR3 is an ISO media file: its raw is the biggest picture
## of its tracks (moov/trak, coded as its CMP1 box says), decoded by cr3's
## CRX codec -- lossless "RAW" and the smaller C-RAW alike, in one tile or
## several -- with its maker and model from CMT1, the sensor's parts from
## CMT3 and the white balance from the timed metadata (CTMD); the CR3s of
## the EOS R, RP, R1, R3, R5, R5 II, R6, R6 II, R7, R8, R10, R50, R100, M50,
## M50 II, M6 II, M200, 90D, 250D, 850D, -1D X III and the PowerShot G5 X II
## and G7 X III have their colors here. Of a dual-pixel CR3 the first picture
## is read, of a CRM movie its first frame, of an HDR PQ CR3 its raw (not the
## HEIF previews). Not read (a `RawError` says so): the sRAW and mRAW CR2s,
## Fujifilm's compressed RAFs and its SuperCCD ones, Nikon's HE NEFs,
## Panasonic's RawFormat 6 to 8, Sony's ARW 6 (compression 32766).

import std/[math, strutils]
import rawphoto, parallel, cr3

export rawphoto

type
  Sensor* = object
    ## A camera's raw picture as it was read: the sensor's numbers, and what
    ## they mean.
    kind*: string               ## "NEF", "ARW", "CR2", ...
    make*, model*: string       ## the camera's maker and model ("NIKON CORPORATION", "NIKON D850")
    rawW*, rawH*: int           ## the numbers: `rawH` rows of `rawW`
    px*: seq[uint16]            ## as the camera wrote them (through its curve, where it has one)
    left*, top*, w*, h*: int    ## the part of them that is the picture
    cfaN*: int                  ## the color mosaic's size: 2 (Bayer) or 6 (X-Trans)
    cfa*: seq[int]              ## its colors (0 red, 1 green, 2 blue), row by row, from the numbers' top left
    black*: array[4, float]     ## the black of each place of the 2 x 2 mosaic (from the top left)
    white*: float               ## a full sensor
    wb*: array[3, float]        ## the white balance as shot: red, green, blue multipliers (0: not known)
    colorMatrix*: array[9, float] ## XYZ (D65) to the camera's colors, row by row (zeros: not known)
    orient*: int                ## EXIF orientation: 1 as is, 3 turned half, 6 and 8 a quarter

proc bad(msg: string) {.noreturn.} = raise newException(RawError, msg)

template fptr(s: seq[float32]): ptr UncheckedArray[float32] =
  cast[ptr UncheckedArray[float32]](if s.len > 0: unsafeAddr s[0] else: nil)

template uptr(s: seq[uint16]): ptr UncheckedArray[uint16] =
  cast[ptr UncheckedArray[uint16]](if s.len > 0: unsafeAddr s[0] else: nil)

# ---- bytes, and TIFF-like directories --------------------------------------------------------------------

type
  Bytes = object
    p: ptr UncheckedArray[uint8]
    n: int

proc bytesOf(s: string): Bytes =
  Bytes(p: cast[ptr UncheckedArray[uint8]](if s.len > 0: unsafeAddr s[0] else: nil), n: s.len)

proc at(b: Bytes; i: int): int {.inline.} =
  if i < 0 or i >= b.n: bad("the file ends early")
  int(b.p[i])

proc text(b: Bytes; i, n: int): string =
  ## `n` bytes as text (cut where the file ends).
  for k in max(0, i) ..< min(b.n, i + n): result.add char(b.p[k])

type
  Rd = object
    ## Reads numbers in a byte order; offsets in directories count from `base`.
    b: Bytes
    le: bool
    base: int
  Tag = object
    tag, kind, count, at: int     ## `at`: where its values are
  Dir = seq[Tag]

proc u16(r: Rd; at: int): int =
  if at < 0 or at + 2 > r.b.n: bad("the file ends early")
  let a = int(r.b.p[at])
  let c = int(r.b.p[at + 1])
  if r.le: a or (c shl 8) else: (a shl 8) or c

proc u32(r: Rd; at: int): int =
  if at < 0 or at + 4 > r.b.n: bad("the file ends early")
  let p = r.b.p
  if r.le: int(p[at]) or (int(p[at + 1]) shl 8) or (int(p[at + 2]) shl 16) or (int(p[at + 3]) shl 24)
  else: (int(p[at]) shl 24) or (int(p[at + 1]) shl 16) or (int(p[at + 2]) shl 8) or int(p[at + 3])

proc s16(r: Rd; at: int): int = (r.u16(at) xor 0x8000) - 0x8000
proc s32(r: Rd; at: int): int = int(cast[int32](uint32(int64(r.u32(at)) and 0xFFFF_FFFF'i64)))

proc kindSize(k: int): int =
  case k
  of 3, 8: 2
  of 4, 9, 11, 13: 4
  of 5, 10, 12: 8
  else: 1

proc dir(r: Rd; at: int): Dir =
  ## The directory at `at` (where it is in the bytes).
  let n = r.u16(at)
  if n == 0 or n > 1000 or at + 2 + 12 * n > r.b.n: bad("a damaged directory")
  for i in 0 ..< n:
    let e = at + 2 + 12 * i
    var t = Tag(tag: r.u16(e), kind: r.u16(e + 2), count: r.u32(e + 4))
    t.at = if kindSize(t.kind) * t.count <= 4: e + 8 else: r.base + r.u32(e + 8)
    result.add t

proc nextDir(r: Rd; at: int): int =
  ## Where the directory after the one at `at` is (0: none).
  let o = r.u32(at + 2 + 12 * r.u16(at))
  if o == 0: 0 else: r.base + o

proc find(d: Dir; tag: int): int =
  for i, t in d:
    if t.tag == tag: return i
  -1

proc num(r: Rd; t: Tag; i = 0): float =
  let at = t.at + i * kindSize(t.kind)
  case t.kind
  of 1, 7, 2: r.b.at(at).float
  of 6: float((r.b.at(at) xor 0x80) - 0x80)
  of 3: r.u16(at).float
  of 8: r.s16(at).float
  of 4, 13: r.u32(at).float
  of 9: r.s32(at).float
  of 5:
    let d = r.u32(at + 4)
    if d == 0: 0.0 else: r.u32(at).float / d.float
  of 10:
    let d = r.s32(at + 4)
    if d == 0: 0.0 else: r.s32(at).float / d.float
  of 11: float(cast[float32](uint32(r.u32(at))))
  else: 0.0

proc get(r: Rd; d: Dir; tag: int; default = 0.0; i = 0): float =
  let k = d.find(tag)
  if k < 0 or i >= d[k].count: default
  else:
    try: r.num(d[k], i) except RawError: default

proc nums(r: Rd; d: Dir; tag: int; most = 1 shl 16): seq[float] =
  let k = d.find(tag)
  if k < 0: return
  for i in 0 ..< min(d[k].count, most):
    try: result.add r.num(d[k], i)
    except RawError: break

proc str(r: Rd; d: Dir; tag: int): string =
  let k = d.find(tag)
  if k < 0: return
  r.b.text(d[k].at, min(d[k].count, 256)).split('\0')[0].strip()

proc tiffOf(b: Bytes; at = 0): Rd =
  ## A TIFF header at `at`: its byte order (its offsets count from `at`).
  if b.n < at + 8: bad("not a raw file")
  if b.p[at] == uint8('I') and b.p[at + 1] == uint8('I'): Rd(b: b, le: true, base: at)
  elif b.p[at] == uint8('M') and b.p[at + 1] == uint8('M'): Rd(b: b, le: false, base: at)
  else: bad("not a raw file")

proc dirsFrom(r: Rd; first: int): seq[Dir] =
  ## The directories chained from `first`, each followed by its
  ## subdirectories (two deep).
  var at = first
  var n = 0
  while at > 0 and n < 12:
    let d = try: r.dir(at) except RawError: break
    result.add d
    for o in r.nums(d, 330, 16):
      let s = try: r.dir(r.base + int(o)) except RawError: continue
      result.add s
      for o2 in r.nums(s, 330, 16):
        try: result.add r.dir(r.base + int(o2))
        except RawError: discard
    let nx = try: r.nextDir(at) except RawError: 0
    if nx == at: break
    at = nx
    inc n

proc exifDir(r: Rd; ifd0: Dir): Dir =
  let k = ifd0.find(34665)
  if k < 0: return
  try: r.dir(r.base + int(r.num(ifd0[k]))) except RawError: @[]

proc makerNote(r: Rd; exif: Dir): (int, int) =
  ## Where the maker's note is, and its length (0, 0: none).
  let k = exif.find(37500)
  if k < 0: (0, 0) else: (exif[k].at, exif[k].count)

# ---- bits ------------------------------------------------------------------------------------------------------

type
  Bits = object
    ## Bits read most significant first (zeros past the end).
    b: Bytes
    pos, stop: int
    acc: uint64
    n: int

proc bitsAt(b: Bytes; at: int; stop = -1): Bits =
  Bits(b: b, pos: at, stop: (if stop < 0: b.n else: min(stop, b.n)))

proc fill(r: var Bits) {.inline.} =
  while r.n <= 56:
    var c = 0'u64
    if r.pos < r.stop:
      c = uint64(r.b.p[r.pos])
      inc r.pos
    r.acc = r.acc or (c shl (56 - r.n))
    r.n += 8

proc peek(r: var Bits; k: int): int {.inline.} =
  if r.n < k: r.fill()
  int(r.acc shr (64 - k))

proc skip(r: var Bits; k: int) {.inline.} =
  r.acc = r.acc shl k
  r.n -= k

proc get(r: var Bits; k: int): int {.inline.} =
  if k <= 0: return 0
  result = r.peek(k)
  r.skip(k)

type
  Huff = object
    ## A Huffman code: the next `bits` bits look up length shl 8 or symbol.
    bits: int
    look: seq[uint16]

proc huffOf(counts: openArray[int]; syms: openArray[int]): Huff =
  ## Codes of each length 1 .. 16 (`counts`), their symbols in order.
  var mx = min(16, counts.len)
  while mx > 0 and counts[mx - 1] == 0: dec mx
  result.bits = max(1, mx)
  result.look = newSeq[uint16](1 shl result.bits)
  var h = 0
  var k = 0
  for l in 1 .. mx:
    for _ in 0 ..< counts[l - 1]:
      let s = if k < syms.len: syms[k] else: 0
      for _ in 0 ..< (1 shl (mx - l)):
        if h < result.look.len:
          result.look[h] = uint16((l shl 8) or (s and 0xFF))
          inc h
      inc k

proc decode(r: var Bits; h: Huff): int {.inline.} =
  let e = int(h.look[r.peek(h.bits)])
  r.skip(e shr 8)
  e and 0xFF

