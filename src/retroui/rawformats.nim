proc sonyDecrypt(buf: var seq[uint8]; key: int) =
  ## Sony's cipher of its private directory (words big-endian, xored).
  var pad: array[128, uint32]
  var k = uint32(key)
  for p in 0 .. 3:
    k = k * 48828125'u32 + 1
    pad[p] = k
  pad[3] = (pad[3] shl 1) or ((pad[0] xor pad[2]) shr 31)
  for p in 4 .. 126:
    pad[p] = ((pad[p - 4] xor pad[p - 2]) shl 1) or ((pad[p - 3] xor pad[p - 1]) shr 31)
  var p = 127
  var i = 0
  while i + 4 <= buf.len:
    pad[p and 127] = pad[(p + 1) and 127] xor pad[(p + 65) and 127]
    let v = pad[p and 127]
    buf[i] = buf[i] xor uint8(v shr 24)
    buf[i + 1] = buf[i + 1] xor uint8((v shr 16) and 255)
    buf[i + 2] = buf[i + 2] xor uint8((v shr 8) and 255)
    buf[i + 3] = buf[i + 3] xor uint8(v and 255)
    inc p
    i += 4

proc sonyArw2(b: Bytes; at, w, h: int; curve: seq[uint16]): seq[uint16] =
  ## Sony's compressed numbers: in blocks of 16 of a color, the biggest and
  ## smallest, and the others as 7 bits above the smallest, through the
  ## camera's curve.
  if at < 0 or at + w * h > b.n: bad("the file ends early")
  result = newSeq[uint16](w * h)
  let rp = uptr(result)
  let cp = uptr(curve)
  let p = b.p
  parallelRows(h, row):
    var pix: array[16, int]
    var q = at + row * w
    var col = 0
    while col < w - 30:
      let val = int(p[q]) or (int(p[q + 1]) shl 8) or (int(p[q + 2]) shl 16) or (int(p[q + 3]) shl 24)
      let mx = val and 0x7ff
      let mn = (val shr 11) and 0x7ff
      let imax = (val shr 22) and 0x0f
      let imin = (val shr 26) and 0x0f
      var sh = 0
      while sh < 4 and (0x80 shl sh) <= mx - mn: inc sh
      var bit = 30
      for i in 0 .. 15:
        if i == imax: pix[i] = mx
        elif i == imin: pix[i] = mn
        else:
          let o = q + (bit shr 3)
          let two = int(p[o]) or (if o + 1 < q + 16: int(p[o + 1]) shl 8 else: 0)
          pix[i] = min(0x7ff, (((two shr (bit and 7)) and 0x7f) shl sh) + mn)
          bit += 7
      for i in 0 .. 15:
        rp[row * w + col] = cp[pix[i] shl 1]
        col += 2
      col -= (if (col and 1) == 1: 1 else: 31)
      q += 16

proc sonyArw1(b: Bytes; at, w, h: int): seq[uint16] =
  ## Sony's first compression (DSLR-A100 .. A350): a running sum of
  ## Huffman-coded differences, column by column from the right, the even
  ## rows and then the odd.
  const tab = [0xf11, 0xf10, 0xe0f, 0xd0e, 0xc0d, 0xb0c, 0xa0b, 0x90a, 0x809,
               0x708, 0x607, 0x506, 0x405, 0x304, 0x303, 0x300, 0x202, 0x201]
  var look = newSeq[uint16](32768)
  var n = 0
  for t in tab:
    for _ in 0 ..< (32768 shr (t shr 8)):
      if n < look.len: look[n] = uint16(t)
      inc n
  result = newSeq[uint16](w * h)
  var r = bitsAt(b, at)
  var sum = 0
  var col = w - 1
  while col >= 0:
    var row = 0
    while row < h + 1:
      if row == h: row = 1
      let e = int(look[r.peek(15)])
      r.skip(e shr 8)
      let s = e and 0xff
      var diff = 0
      if s == 16: diff = -32768
      elif s > 0:
        diff = r.get(s)
        if (diff and (1 shl (s - 1))) == 0: diff -= (1 shl s) - 1
      sum += diff
      if row < h: result[row * w + col] = uint16(sum and 0xFFFF)
      row += 2
    dec col

proc sonyTiles(b: Bytes; r: Rd; d: Dir; w, h: int): seq[uint16] =
  ## Sony's lossless compression: tiles of lossless JPEG, each sample four
  ## numbers of a 2 x 2.
  let tw = int(r.get(d, 322))
  let th = int(r.get(d, 323))
  let offs = r.nums(d, 324)
  let cnts = r.nums(d, 325)
  if tw <= 0 or th <= 0 or offs.len == 0: bad("a damaged ARW")
  result = newSeq[uint16](w * h)
  let across = (w + tw - 1) div tw
  var s = ""
  for k in 0 ..< offs.len:
    let ty = (k div across) * th
    let tx = (k mod across) * tw
    let o = int(offs[k])
    let n = if k < cnts.len: int(cnts[k]) else: b.n - o
    if o < 0 or n <= 0 or o + n > b.n: bad("the file ends early")
    s.setLen(n)
    copyMem(addr s[0], addr b.p[o], n)
    let j = decodeLj92(s, 0, n)
    if j.comps != 4: bad("an ARW tile of a kind we do not read")
    for jr in 0 ..< j.h:
      let y = ty + 2 * jr
      if y + 1 >= h: break
      for jc in 0 ..< j.w:
        let x = tx + 2 * jc
        if x + 1 >= w: break
        let q = (jr * j.w + jc) * 4
        result[y * w + x] = j.px[q]
        result[y * w + x + 1] = j.px[q + 1]
        result[(y + 1) * w + x] = j.px[q + 2]
        result[(y + 1) * w + x + 1] = j.px[q + 3]

proc readArw(data: string; b: Bytes): Sensor =
  let r = tiffOf(b)
  let first = r.base + r.u32(4)
  let ifd0 = r.dir(first)
  result.start(r, ifd0, "ARW")
  let dirs = r.dirsFrom(first)
  let raw = r.mosaicDir(dirs)
  let w = int(r.get(raw, 256))
  let h = int(r.get(raw, 257))
  let comp = int(r.get(raw, 259, 1))
  result.rawW = w
  result.rawH = h
  result.cfaOf(r, raw, [0, 1, 1, 2])
  # the curve (compressed files)
  var curve = newSeq[uint16](0x10000)
  for i in 0 ..< curve.len: curve[i] = uint16(i)
  for d in dirs:
    let k = d.find(0x7010)
    if k >= 0 and d[k].count >= 4:
      var sc = [0, 0, 0, 0, 0, 4095]
      for c in 0 .. 3: sc[c + 1] = (r.u16(d[k].at + 2 * c) shr 2) and 0xfff
      for i in 0 .. 4:
        for j in sc[i] + 1 .. sc[i + 1]: curve[j] = curve[j - 1] + uint16(1 shl i)
      break
  # the private directory: white balance, black, white
  var wb4: array[4, float]          # red, green, blue, green
  var black4 = [512.0, 512, 512, 512]
  var white = 0.0
  let pk = ifd0.find(0xc634)
  if pk >= 0:
    try:
      let sr2 = r.dir(r.base + r.u32(ifd0[pk].at))
      let off = int(r.get(sr2, 0x7200))
      let len = int(r.get(sr2, 0x7201))
      let kk = sr2.find(0x7221)
      let key = if kk >= 0: r.u32(sr2[kk].at) else: 0
      if len > 0 and len < 10_000_000 and off + len <= b.n:
        var buf = newSeq[uint8](len)
        copyMem(addr buf[0], addr b.p[off], len)
        sonyDecrypt(buf, key)
        let sb = Bytes(p: cast[ptr UncheckedArray[uint8]](addr buf[0]), n: len)
        let sr = Rd(b: sb, le: r.le, base: -off)
        let sd = sr.dir(0)
        for t in sd:
          case t.tag
          of 0x7303:
            for c in 0 .. 3: wb4[[1, 0, 2, 3][c]] = sr.num(t, c)
          of 0x7313:
            for c in 0 .. 3: wb4[[0, 1, 3, 2][c]] = sr.num(t, c)
          of 0x7310, 0x7300:
            for c in 0 .. 3: black4[c] = sr.num(t, c)
          of 0x787f:
            white = sr.num(t, 0)
          else: discard
    except RawError: discard
  # the numbers
  let (at, size) = r.stripsOf(raw)
  if comp == 32767 and size == w * h: result.px = sonyArw2(b, at, w, h, curve)
  elif comp in [1, 32767] and size >= w * h * 2: result.px = unpacked(b, at, w, h, r.le)
  elif comp == 7: result.px = sonyTiles(b, r, raw, w, h)
  elif comp == 32767 and size * 8 != w * h * int(r.get(raw, 258, 12)):
    # (the first ARWs: eight more rows than they say)
    result.rawH = h + 8
    result.px = sonyArw1(b, at, w, h + 8)
  else: bad("an ARW of a kind we do not read (" & $comp & ")")
  let ab = adobeOf(result.make, result.model)
  result.colorMatrix = ab.m
  # (black: red, green, green, blue -> each place of the mosaic)
  for k in 0 .. 3:
    let c = result.cfa[k]
    result.black[k] = case c
                      of 0: black4[0]
                      of 2: black4[3]
                      else: (if result.cfa[k xor 1] == 2: black4[2] else: black4[1])
  result.white = if ab.found and ab.white > 0: ab.white.float
                 elif result.rawH != h: 4095           # (the first ARWs: 12 bits)
                 elif white > 0: white
                 else: 16383
  if wb4[0] > 0 and wb4[1] > 0 and wb4[2] > 0: result.wb = [wb4[0], wb4[1], wb4[2]]
  # the picture's part: Adobe's crop tags, else all
  let co = r.nums(raw, 0xc61f)
  let cs = r.nums(raw, 0xc620)
  result.left = 0
  result.top = 0
  result.w = w
  result.h = result.rawH
  if co.len == 2 and cs.len == 2 and co[0] + cs[0] <= w.float and co[1] + cs[1] <= h.float:
    result.left = int(co[0])
    result.top = int(co[1])
    result.w = int(cs[0])
    result.h = int(cs[1])
  else:
    # (the columns on the right that are not picture, as LibRaw knows them)
    let md = normalModel("Sony", result.model)
    result.w -= (case w
                 of 4288: 32
                 of 4928: (if h < 3280: 8 else: 0)
                 of 5504: (if h > 3664: 8 else: 32)
                 of 6048: (if "RX1" in md or "A99" in md: 30 else: 24)
                 of 7392: 30
                 of 8000, 9600: 32
                 else: 0)

