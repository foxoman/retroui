proc readCr2(data: string; b: Bytes): Sensor =
  let r = tiffOf(b)
  let first = r.base + r.u32(4)
  let ifd0 = r.dir(first)
  result.start(r, ifd0, "CR2")
  # the raw: the lossless JPEG the last directories point to
  var raw: Dir
  var found = false
  var at, size, prec: int
  for d in r.dirsFrom(first):
    let offs = r.nums(d, 273)
    let cnts = r.nums(d, 279)
    if offs.len != 1 or cnts.len != 1: continue
    let o = int(offs[0])
    if o + 4 > b.n or b.p[o] != 0xFF or b.p[o + 1] != 0xD8: continue
    # (a lossless one: an SOF3 before the scan)
    var q = o + 2
    var lossless = false
    var pr = 0
    while q + 4 <= min(b.n, o + 4096) and b.p[q] == 0xFF:
      let mk = int(b.p[q + 1])
      if mk == 0xC3:
        lossless = true
        pr = int(b.p[q + 4])
        let samp = int(b.p[q + 11])
        if (samp shr 4) * (samp and 15) > 1: bad("a Canon sRAW or mRAW (not a mosaic), which we do not read")
      if mk == 0xDA: break
      q += 2 + ((int(b.p[q + 2]) shl 8) or int(b.p[q + 3]))
    if lossless and int(cnts[0]) > size:
      raw = d
      prec = pr
      at = o
      size = int(cnts[0])
      found = true
  if not found: bad("no raw picture in the CR2")
  let j = decodeLj92(data, at, size)
  var w = j.w * j.comps
  var h = j.h
  if w > 4 * h and (j.comps and 1) == 0:
    w = w div 2
    h = h * 2
  result.rawW = w
  result.rawH = h
  result.px = newSeq[uint16](w * h)
  let slices = r.nums(raw, 0xc640)
  if slices.len == 3 and slices[0] >= 0 and slices[1] > 0 and slices[2] > 0:
    # (the picture in slices side by side, each one row after row)
    let ns = int(slices[0])
    let sw = int(slices[1])
    let lw = int(slices[2])
    let rp = uptr(result.px)
    let jp = cast[ptr UncheckedArray[uint16]](unsafeAddr j.px[0])
    let total = min(j.px.len, w * h)
    let per = sw * h
    parallelChunks(total, lo, hi):
      for idx in lo ..< hi:
        var i = idx div per
        var k = idx
        var width = sw
        if i >= ns:
          i = ns
          width = lw
        k -= i * per
        let row = k div width
        let col = k mod width + i * sw
        if row < h and col < w: rp[row * w + col] = jp[idx]
  else:
    for i in 0 ..< min(j.px.len, w * h): result.px[i] = j.px[i]
  # the maker's note: the sensor's parts, white balance
  var left, top, right, bottom = -1
  var wb4: array[4, float]
  let (mn, _) = r.makerNote(r.exifDir(ifd0))
  if mn > 0:
    try:
      let md = r.dir(mn)
      for t in md:
        case t.tag
        of 0xe0:
          if t.count >= 9 and int(r.num(t, 1)) == w and int(r.num(t, 2)) == h:
            left = int(r.num(t, 5))
            top = int(r.num(t, 6))
            right = int(r.num(t, 7))
            bottom = int(r.num(t, 8))
        of 0x4001:
          if t.count > 500:
            let k = case t.count
                    of 582: 0x19
                    of 653: 0x22
                    of 5120, 1816, 1820, 1824: 0x47
                    of 2024, 3656: 0x55
                    of 3973, 3778, 4528: 0x69
                    else: 0x3f
            for c in 0 .. 3: wb4[[0, 1, 3, 2][c]] = r.num(t, k + c)
        else: discard
    except RawError: discard
  # the picture's part, and the mosaic: red at its top left (as dcraw and
  # LibRaw know Canon's sensors), else the camera's own borders
  var base = [0, 1, 1, 2]
  var known = false
  for t in canonSensors:
    if t[0] == w and t[1] == h:
      result.left = t[2]
      result.top = t[3]
      result.w = w - t[2] - t[4]
      result.h = h - t[3] - t[5]
      if t[10] == 0x49: base = [1, 2, 0, 1]
      known = true
      break
  if not known:
    if left >= 0 and right > left and bottom > top:
      result.left = (left + 1) and not 1
      result.top = (top + 1) and not 1
      result.w = right - result.left
      result.h = bottom - result.top
    else:
      result.left = 0
      result.top = 0
      result.w = w
      result.h = h
  result.cfa = newSeq[int](4)
  for yy in 0 .. 1:
    for xx in 0 .. 1: result.cfa[yy * 2 + xx] = base[((yy - result.top) and 1) * 2 + ((xx - result.left) and 1)]
  # black: the masked columns beside the picture
  var sum: array[4, float]
  var cnt: array[4, int]
  for y in result.top ..< result.top + result.h:
    for x in 2 ..< result.left - 2:
      let k = (y and 1) * 2 + (x and 1)
      sum[k] += float(result.px[y * w + x])
      inc cnt[k]
    for x in result.left + result.w + 2 ..< w:
      let k = (y and 1) * 2 + (x and 1)
      sum[k] += float(result.px[y * w + x])
      inc cnt[k]
  for k in 0 .. 3:
    result.black[k] = if cnt[k] > 0: floor(sum[k] / cnt[k].float) else: 0
  let ab = adobeOf(result.make, result.model)
  result.colorMatrix = ab.m
  result.white = if ab.found and ab.white > 0: ab.white.float else: float((1 shl clamp(prec, 8, 16)) - 1)
  if wb4[0] > 0 and wb4[1] > 0 and wb4[2] > 0: result.wb = [wb4[0], wb4[1], wb4[2]]

