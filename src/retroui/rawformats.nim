type
  XNeighbors = object
    ## For each place of the 6 x 6 mosaic and each color: where its nearest
    ## pixels of that color are, and how much each counts.
    first, count: array[36, array[3, int]]
    dx, dy: seq[int]
    wt: seq[float32]

proc xNeighbors(cfa: seq[int]): XNeighbors =
  for p in 0 .. 35:
    let (py, px) = (p div 6, p mod 6)
    for c in 0 .. 2:
      result.first[p][c] = result.dx.len
      var reach = 1
      while reach <= 2 and result.dx.len == result.first[p][c]:
        for dy in -reach .. reach:
          for dx in -reach .. reach:
            if dx == 0 and dy == 0: continue
            if cfa[((py + dy + 6) mod 6) * 6 + ((px + dx + 6) mod 6)] != c: continue
            result.dx.add dx
            result.dy.add dy
            # (green: across and up count twice the corners; red and blue: by nearness)
            result.wt.add(if c == 1: (if dx == 0 or dy == 0: 2'f32 else: 1'f32)
                          else: 1'f32 / float32(1 + dx * dx + dy * dy))
        inc reach
      result.count[p][c] = result.dx.len - result.first[p][c]

proc xtransLight(lin: seq[float32]; w, h: int; cfa: seq[int]; mu: array[3, float32]; m: array[9, float32];
                 orient: int): seq[float32] =
  ## The 6 x 6 mosaic (Fujifilm's X-Trans) filled in -- green from the
  ## greens around, red and blue as their difference from green around --
  ## white balanced, made sRGB and turned.
  let nb = xNeighbors(cfa)
  let pat = cfa
  let pp = cast[ptr UncheckedArray[int]](unsafeAddr pat[0])
  let ndx = cast[ptr UncheckedArray[int]](unsafeAddr nb.dx[0])
  let ndy = cast[ptr UncheckedArray[int]](unsafeAddr nb.dy[0])
  let nwt = cast[ptr UncheckedArray[float32]](unsafeAddr nb.wt[0])
  let mp = fptr(lin)
  var green = newSeq[float32](w * h)
  let gp = fptr(green)
  parallelRows(h, y):
    for x in 0 ..< w:
      let p = (y mod 6) * 6 + (x mod 6)
      if pp[p] == 1:
        gp[y * w + x] = mp[y * w + x]
      else:
        var s = 0'f32
        var n = 0'f32
        let f = nb.first[p][1]
        for k in f ..< f + nb.count[p][1]:
          let yy = y + ndy[k]
          let xx = x + ndx[k]
          if yy >= 0 and yy < h and xx >= 0 and xx < w:
            s += mp[yy * w + xx] * nwt[k]
            n += nwt[k]
        gp[y * w + x] = if n > 0: s / n else: mp[y * w + x]
  let (ow, oh) = if orient in [6, 8]: (h, w) else: (w, h)
  result = newSeq[float32](ow * oh * 3)
  let op = fptr(result)
  const T = 64
  let tx = (w + T - 1) div T
  let ty = (h + T - 1) div T
  parallelChunks(tx * ty, lo, hi):
    for t in lo ..< hi:
      let y0 = (t div tx) * T
      let x0 = (t mod tx) * T
      for y in y0 ..< min(h, y0 + T):
        for x in x0 ..< min(w, x0 + T):
          let p = (y mod 6) * 6 + (x mod 6)
          let c = pp[p]
          let g = gp[y * w + x]
          var rgb: array[3, float32]
          rgb[1] = g
          for want in 0 .. 2:
            if want == 1: continue
            if want == c:
              rgb[want] = mp[y * w + x]
              continue
            var s = 0'f32
            var n = 0'f32
            let f = nb.first[p][want]
            for k in f ..< f + nb.count[p][want]:
              let yy = y + ndy[k]
              let xx = x + ndx[k]
              if yy >= 0 and yy < h and xx >= 0 and xx < w:
                s += (mp[yy * w + xx] - gp[yy * w + xx]) * nwt[k]
                n += nwt[k]
            rgb[want] = max(0'f32, g + (if n > 0: s / n else: 0'f32))
          let r = min(1'f32, rgb[0] * mu[0])
          let gg = min(1'f32, rgb[1] * mu[1])
          let b = min(1'f32, rgb[2] * mu[2])
          var nx = x
          var ny = y
          if orient == 3:
            nx = w - 1 - x
            ny = h - 1 - y
          elif orient == 6:
            nx = h - 1 - y
            ny = x
          elif orient == 8:
            nx = y
            ny = w - 1 - x
          let o = (ny * ow + nx) * 3
          op[o] = max(0'f32, m[0] * r + m[1] * gg + m[2] * b)
          op[o + 1] = max(0'f32, m[3] * r + m[4] * gg + m[5] * b)
          op[o + 2] = max(0'f32, m[6] * r + m[7] * gg + m[8] * b)

template mhc(mp: ptr UncheckedArray[float32]; w, h, x, y: int; cfa: array[4, int]; r, g, b: var float32;
              X: untyped) =
  ## Malvar, He and Cutler's colors of pixel `x`, `y` (rawphoto's
  ## `demosaic`), its neighbors read with `X`.
  let c = cfa[(y and 1) * 2 + (x and 1)]
  let v = X(x, y)
  if c == 1:
    g = v
    let across = cfa[(y and 1) * 2 + ((x + 1) and 1)]
    let diag = X(x - 1, y - 1) + X(x + 1, y - 1) + X(x - 1, y + 1) + X(x + 1, y + 1)
    let horiz = (5 * v + 4 * (X(x - 1, y) + X(x + 1, y)) - X(x - 2, y) - X(x + 2, y) - diag +
                 0.5'f32 * (X(x, y - 2) + X(x, y + 2))) / 8
    let vert = (5 * v + 4 * (X(x, y - 1) + X(x, y + 1)) - X(x, y - 2) - X(x, y + 2) - diag +
                0.5'f32 * (X(x - 2, y) + X(x + 2, y))) / 8
    if across == 0:
      r = horiz
      b = vert
    else:
      b = horiz
      r = vert
  else:
    let far = X(x - 2, y) + X(x + 2, y) + X(x, y - 2) + X(x, y + 2)
    g = (4 * v + 2 * (X(x - 1, y) + X(x + 1, y) + X(x, y - 1) + X(x, y + 1)) - far) / 8
    let other = (6 * v + 2 * (X(x - 1, y - 1) + X(x + 1, y - 1) + X(x - 1, y + 1) + X(x + 1, y + 1)) -
                 1.5'f32 * far) / 8
    if c == 0:
      r = v
      b = other
    else:
      b = v
      r = other
  r = max(0'f32, r)
  g = max(0'f32, g)
  b = max(0'f32, b)

proc bayerLight(lin: seq[float32]; w, h: int; cfa: array[4, int]; mu: array[3, float32]; m: array[9, float32];
                orient: int): seq[float32] =
  ## The 2 x 2 mosaic filled in (Malvar-He-Cutler), white balanced, made
  ## sRGB and turned, in one pass, tile by tile.
  let (ow, oh) = if orient in [6, 8]: (h, w) else: (w, h)
  result = newSeq[float32](ow * oh * 3)
  const T = 64
  let tx = (w + T - 1) div T
  let ty = (h + T - 1) div T
  let mp = fptr(lin)
  let op = fptr(result)
  parallelChunks(tx * ty, lo, hi):
    for t in lo ..< hi:
      let y0 = (t div tx) * T
      let x0 = (t mod tx) * T
      for y in y0 ..< min(h, y0 + T):
        let inner = y >= 2 and y < h - 2
        for x in x0 ..< min(w, x0 + T):
          var r, g, b: float32
          if inner and x >= 2 and x < w - 2:
            template F(xx, yy: int): float32 = mp[(yy) * w + (xx)]
            mhc(mp, w, h, x, y, cfa, r, g, b, F)
          else:
            template C(xx, yy: int): float32 = mp[clamp(yy, 0, h - 1) * w + clamp(xx, 0, w - 1)]
            mhc(mp, w, h, x, y, cfa, r, g, b, C)
          # (white balanced, cut where the sensor was full: no colored highlights)
          r = min(1'f32, r * mu[0])
          g = min(1'f32, g * mu[1])
          b = min(1'f32, b * mu[2])
          var nx = x
          var ny = y
          if orient == 3:
            nx = w - 1 - x
            ny = h - 1 - y
          elif orient == 6:
            nx = h - 1 - y
            ny = x
          elif orient == 8:
            nx = y
            ny = w - 1 - x
          let o = (ny * ow + nx) * 3
          op[o] = max(0'f32, m[0] * r + m[1] * g + m[2] * b)
          op[o + 1] = max(0'f32, m[3] * r + m[4] * g + m[5] * b)
          op[o + 2] = max(0'f32, m[6] * r + m[7] * g + m[8] * b)

proc develop*(s: Sensor): RawImage =
  ## The sensor's numbers made light as rawphoto's DNGs are (see
  ## `RawImage`): black and white levels, the mosaic filled in, the white
  ## balance as shot, the camera's colors made sRGB's, turned as the
  ## camera was held.
  if s.w <= 0 or s.h <= 0 or s.left < 0 or s.top < 0 or s.left + s.w > s.rawW or s.top + s.h > s.rawH or
     s.px.len < s.rawW * s.rawH:
    bad("a raw picture of a size we do not read")
  if s.cfaN notin [2, 6] or s.cfa.len != s.cfaN * s.cfaN: bad("a color mosaic we do not read")
  result.make = s.make
  result.model = s.model
  let cw = s.w
  let ch = s.h
  # the camera's colors made sRGB's (dcraw's way), and the white balance
  var cm = s.colorMatrix
  var any = false
  for v in cm:
    if v != 0: any = true
  if not any: cm = adobeOf(s.make, s.model).m
  const xyzRgb = [0.412453, 0.357580, 0.180423, 0.212671, 0.715160, 0.072169, 0.019334, 0.119193, 0.950227]
  var camRgb: array[9, float]
  for r in 0 .. 2:
    for c in 0 .. 2:
      camRgb[r * 3 + c] = cm[r * 3] * xyzRgb[c] + cm[r * 3 + 1] * xyzRgb[3 + c] + cm[r * 3 + 2] * xyzRgb[6 + c]
  var daylight: array[3, float]
  for r in 0 .. 2:
    let t = camRgb[r * 3] + camRgb[r * 3 + 1] + camRgb[r * 3 + 2]
    daylight[r] = if abs(t) > 1e-9: 1 / t else: 1.0
    if abs(t) > 1e-9:
      for c in 0 .. 2: camRgb[r * 3 + c] /= t
  let m64 = inv3(camRgb)
  var m: array[9, float32]
  for i in 0 .. 8: m[i] = float32(m64[i])
  var mul = s.wb
  if mul[0] <= 0 or mul[1] <= 0 or mul[2] <= 0: mul = daylight
  var mu: array[3, float32]
  for c in 0 .. 2: mu[c] = float32(mul[c] / mul[1])
  # linear: black 0, white 1
  var lin = newSeq[float32](cw * ch)
  var bl, sc: array[4, float32]
  for k in 0 .. 3:
    bl[k] = float32(s.black[k])
    sc[k] = float32(1 / max(1.0, s.white - s.black[k]))
  let sp = uptr(s.px)
  let lp = fptr(lin)
  let rw = s.rawW
  let (x0, y0) = (s.left, s.top)
  parallelRows(ch, y):
    let sy = y0 + y
    let k0 = (sy and 1) * 2 + (x0 and 1)
    let k1 = k0 xor 1
    let row = sy * rw + x0
    var x = 0
    while x + 1 < cw:
      lp[y * cw + x] = max(0'f32, (float32(sp[row + x]) - bl[k0]) * sc[k0])
      lp[y * cw + x + 1] = max(0'f32, (float32(sp[row + x + 1]) - bl[k1]) * sc[k1])
      x += 2
    if x < cw: lp[y * cw + x] = max(0'f32, (float32(sp[row + x]) - bl[k0]) * sc[k0])
  # the mosaic filled in (its colors from the picture's top left), the colors, turned
  var ow = cw
  var oh = ch
  if s.orient in [6, 8]: swap(ow, oh)
  if s.cfaN == 2:
    var cfa: array[4, int]
    for yy in 0 .. 1:
      for xx in 0 .. 1: cfa[yy * 2 + xx] = s.cfa[((yy + y0) and 1) * 2 + ((xx + x0) and 1)]
    result.px = bayerLight(lin, cw, ch, cfa, mu, m, s.orient)
  else:
    var cfa = newSeq[int](36)
    for yy in 0 .. 5:
      for xx in 0 .. 5: cfa[yy * 6 + xx] = s.cfa[((yy + y0) mod 6) * 6 + ((xx + x0) mod 6)]
    result.px = xtransLight(lin, cw, ch, cfa, mu, m, s.orient)
  result.w = ow
  result.h = oh

