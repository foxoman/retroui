proc pentaxHuffman(b: Bytes; m: Rd; meta, at, w, h: int): seq[uint16] =
  ## Pentax's compressed numbers: Huffman-coded differences (lossless JPEG's
  ## kind) from the same color two pixels back, two rows up at a row's
  ## start; the code is in the maker's note.
  let dep = (m.u16(meta) + 12) and 15
  var codes, lens: array[16, int]
  for c in 0 ..< dep: codes[c] = m.u16(meta + 14 + 2 * c)
  for c in 0 ..< dep: lens[c] = m.b.at(meta + 14 + 2 * dep + c)
  var look = newSeq[uint16](4096)
  for c in 0 ..< dep:
    let l = lens[c]
    if l <= 0 or l > 12: continue
    let stop = (codes[c] + (4096 shr l) - 1) and 4095
    var i = codes[c]
    while i <= stop and i < 4096:
      look[i] = uint16((l shl 8) or c)
      inc i
  result = newSeq[uint16](w * h)
  var r = bitsAt(b, at)
  var vpred: array[2, array[2, int]]
  var hpred: array[2, int]
  let rp = uptr(result)
  for row in 0 ..< h:
    for col in 0 ..< w:
      let e = int(look[r.peek(12)])
      let len = e shr 8
      r.skip(len)
      let s = e and 0xFF
      var diff = 0
      if s == 16: diff = -32768
      elif s > 0:
        diff = r.get(s)
        if (diff and (1 shl (s - 1))) == 0: diff -= (1 shl s) - 1
      if col < 2:
        vpred[row and 1][col] = (vpred[row and 1][col] + diff) and 0xFFFF
        hpred[col] = vpred[row and 1][col]
      else:
        hpred[col and 1] = (hpred[col and 1] + diff) and 0xFFFF
      rp[row * w + col] = uint16(hpred[col and 1])

proc readPef(data: string; b: Bytes): Sensor =
  let r = tiffOf(b)
  let first = r.base + r.u32(4)
  let ifd0 = r.dir(first)
  result.start(r, ifd0, "PEF")
  let dirs = r.dirsFrom(first)
  var raw: Dir
  var best = 0
  for d in dirs:
    let a = int(r.get(d, 256)) * int(r.get(d, 257))
    let comp = int(r.get(d, 259, 1))
    if a > best and comp in [1, 65535] and int(r.get(d, 277, 1)) == 1 and r.nums(d, 273).len > 0:
      best = a
      raw = d
  if best == 0: bad("no raw picture in the PEF")
  let w = int(r.get(raw, 256))
  let h = int(r.get(raw, 257))
  let bps = int(r.get(raw, 258, 12))
  let comp = int(r.get(raw, 259, 1))
  let (at, size) = r.stripsOf(raw)
  result.rawW = w
  result.rawH = h
  result.cfaOf(r, raw, [0, 1, 1, 2])
  let exif = r.exifDir(ifd0)
  if result.cfa == @[0, 1, 1, 2]:
    let ecfa = r.exifCfa(exif)
    if ecfa.len == 4: result.cfa = ecfa
  var wb4: array[4, float]
  var black4: array[4, float]
  var meta = -1
  var mr = r
  let (mn, _) = r.makerNote(exif)
  if mn > 0:
    try:
      var md: Dir
      if data.continuesWith("AOC\0", mn):
        md = r.dir(mn + 6)
      elif data.continuesWith("PENTAX \0", mn) or data.continuesWith("RICOH\0", mn):
        mr = Rd(b: b, le: data[mn + 8] == 'I', base: mn)
        md = mr.dir(mn + 10)
      for tg in md:
        case tg.tag
        of 0x0200:
          if tg.count >= 4:
            for c in 0 .. 3: black4[c] = mr.num(tg, c)
        of 0x0201:
          if tg.count >= 4:
            for c in 0 .. 3: wb4[c] = mr.num(tg, c)
        of 0x0220: meta = tg.at
        else: discard
    except RawError: discard
  if comp == 65535:
    if meta < 0: bad("a compressed PEF without its code")
    result.px = pentaxHuffman(b, mr, meta, at, w, h)
  elif size >= w * h * 2: result.px = unpacked(b, at, w, h, r.le)
  elif size >= (w * bps + 7) div 8 * h: result.px = packedMsb(b, at, w, h, bps)
  else: bad("a PEF of a kind we do not read")
  let ab = adobeOf(result.make, result.model)
  result.colorMatrix = ab.m
  # (black and white balance: red, green, green, blue -> each place of the mosaic)
  for k in 0 .. 3:
    let c = result.cfa[k]
    result.black[k] = case c
                      of 0: black4[0]
                      of 2: black4[3]
                      else: (if result.cfa[k xor 1] == 2: black4[2] else: black4[1])
  if ab.found and ab.black > 0:
    for v in result.black.mitems: v = ab.black.float
  result.white = if ab.found and ab.white > 0: ab.white.float else: float((1 shl bps) - 1)
  if wb4[0] > 0 and wb4[1] > 0 and wb4[3] > 0: result.wb = [wb4[0], wb4[1], wb4[3]]
  # the picture's part (as LibRaw knows Pentax's)
  result.left = 0
  result.top = 0
  result.w = w
  result.h = h
  let md = normalModel("Pentax", result.model)
  if md.startsWith("K-1") and w == 7392:
    result.top = 18
    result.h = h - 18
    result.left = 6
    result.w = 7376
  elif md.startsWith("K-1"):
    result.top = 18
    result.h = h - 18
  elif h == 2624 and w == 3936:
    result.h = 2616
    result.w = 3896
  elif h == 3136 and w == 4864:
    result.h = 3124
    result.w = 4688
  elif (md == "K-r" or md == "K-x") and w == 4352:
    result.w = 4309
  elif md.startsWith("K-5") and w >= 4960:
    result.left = 10
    result.w = 4950
  elif (md == "K-3" or md == "K-3 II") and w == 6080:
    result.left = 4
    result.w = 6040
  elif md.startsWith("K-3 Mark III") and w == 6304:
    result.left = 26
    result.w = 6224
    result.top = 34
    result.h = 4160
  elif md == "K-70" and w == 6080:
    result.top = 32
    result.h = 4016
    result.left = 60
    result.w = 6020
  elif md == "KP" and w == 6112:
    result.left = 54
    result.top = 28
    result.w = 6028
    result.h = h - 28
  elif md == "K-7" and w == 4736:
    result.h = 3122
    result.w = 4684
    result.top = 2

